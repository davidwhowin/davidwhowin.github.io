/**
 * QA helper: render `seconds` of one song offline (OfflineAudioContext) and report levels.
 * Not used by the game. Runs the same step sequencer straight into a bus at the in-game music level.
 */
export async function renderTrackOffline(id, seconds = 20, sampleRate = 44100, calm = false, keepBuffer = false) {
  const OAC = (typeof window !== 'undefined') && (window.OfflineAudioContext || window.webkitOfflineAudioContext);
  const track = TRACK_BY_ID[id];
  if (!OAC || !track) return null;
  const ac = new OAC(2, Math.ceil((seconds + 4) * sampleRate), sampleRate);
  const bus = ac.createGain(); bus.gain.value = calm ? MUSIC_VOL * 0.55 : MUSIC_VOL; bus.connect(ac.destination);
  const verbIn = buildMusicVerb(ac, bus);
  const S = newSession(ac, track, bus, verbIn, 0);
  S.nextAt = 0.05;
  scheduleUntil(S, seconds, calm);
  const buf = await ac.startRendering();
  let peak = 0, sum = 0, n = 0, clipped = 0;
  const win = Math.floor(sampleRate * 0.5);
  let silentWins = 0, winPeak = 0;
  const L = buf.getChannelData(0), Rch = buf.getChannelData(1);
  const last = Math.floor(seconds * sampleRate);
  for (let i = 0; i < last; i++) {
    const v = Math.max(Math.abs(L[i]), Math.abs(Rch[i]));
    if (!Number.isFinite(v)) { clipped++; continue; }
    if (v > peak) peak = v;
    if (v >= 1) clipped++;
    sum += L[i] * L[i] + Rch[i] * Rch[i]; n += 2;
    if (v > winPeak) winPeak = v;
    if ((i + 1) % win === 0) { if (i > sampleRate * 3 && winPeak < 0.001) silentWins++; winPeak = 0; }
  }
  const db = (v) => (v > 0 ? Math.round(200 * Math.log10(v)) / 10 : -Infinity);
  const rms = Math.sqrt(sum / Math.max(1, n));
  const loopSec = (track.chords.length * track.chordSteps * 60) / track.bpm / track.div;
  return { ...(keepBuffer ? { buffer: buf } : null), id, seconds, loopSec: Math.round(loopSec * 10) / 10, peak: Math.round(peak * 1000) / 1000, peakDb: db(peak), rmsDb: db(rms), clipped, silentHalfSeconds: silentWins };
}

