// on the same music bus, so the Music switch, music volume, Calm / evening softening, ducking for big
// moments, hidden-tab pause and the one-owner rule all apply unchanged. Switching fades over 1.5 s.

const BED_FADE = 1.5;
const BED_IDS = ['music', ...AMBIENCE_IDS, 'silence'];
let bedId = 'music';
let amb = null;                 // the live backdrop session (at most one)
const fadingAmb = new Set();    // backdrops inside their fade-out
let previewAmb = null;          // a 3 s Settings preview while the bed itself is silent

/** The bed that should sound now: a song previewed in the Tracks sheet plays even under a backdrop. */
function activeBed() { return previewId ? 'music' : nightWaves ? 'ocean' : bedId; }

function endAmb(fade = BED_FADE) {
  const A = amb;
  amb = null;
  if (!A) return;
  // Rapid chip tapping: keep at most two backdrops fading (CPU); the oldest is nearly silent by then.
  if (fadingAmb.size >= 2) { const old = fadingAmb.values().next().value; old.finish(); fadingAmb.delete(old); }
  fadingAmb.add(A);
  A.end(fade);
  setTimeout(() => { A.finish(); fadingAmb.delete(A); }, (fade + 0.4) * 1000);
}

/** Music timer tick while a backdrop (or Silence) is the bed: songs fade out, the backdrop schedules ahead. */
function bedTick() {
  if (liveSessions.size) endAllSessions(BED_FADE);
  cur = null;
  const want = activeBed();
  if (amb && amb.id !== want) endAmb(BED_FADE);
  if (!amb && want !== 'silence' && AMBIENCE_IDS.includes(want)) {
    amb = createAmbience(ctx, want, musicBus, musicVerbIn || null, { fadeIn: BED_FADE });
  }
  if (amb) { try { amb.tick(ctx.currentTime + LOOKAHEAD); } catch (_) { /* never let audio break the game */ } }
}

