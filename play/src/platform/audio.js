// Music: seven fully synthesized seaside-café songs (no audio files).
// Every song stays on the white keys (C major / A minor / D dorian / G mixolydian / F lydian colours), so the
// C-major stingers and merge notes are always in key. One song is picked per run or level attempt
// (Math.random only, never the game's seeded RNG) and loops for the whole run. With the evening look or Calm
// on, the pick prefers the three quiet evening songs.
// Each song is a small step sequencer over a 16-bar form: a written, hummable LEAD MELODY on the song's own
// signature instrument (it starts on the very first beat, so a song is recognisable within two seconds),
// real chords with 7ths and 9ths, an upright-bass line and, on the daytime songs, soft brushes and shaker.
// The form is two halves: bars 1-8 state the tune, bars 9-16 answer it with a second strain and a fuller
// arrangement (glockenspiel, walking bass, a second lead voice), so a loop never sounds like a plain copy.
// No kick drums, no driving beats: everything sits between 70 and 100 BPM.

const MUSIC_WET = 0.32 / 0.11; // reverb return (sits inside musicBus); balance set when MUSIC_VOL was 0.11
const LOOKAHEAD = 0.6;
let musicTimer = null;
let cur = null;                // current song session { id, ac, track, dry, wet, noise, stepIdx, nextAt, dead, sources }
const liveSessions = new Set(); // every song that is not ending (should hold at most one)
const fadingSessions = new Set(); // ended songs still inside their fade-out
let sessionSeq = 0;
let currentId = null;          // chosen lazily from the ENABLED songs (never a fixed default)
let enabledMap = null;         // { id: bool }, missing = on

function buildMusicVerb(ac, dest) {
  const conv = ac.createConvolver();
  conv.buffer = makeImpulse(1.6, 3.2, ac);
  const lp = ac.createBiquadFilter(); lp.type = 'lowpass'; lp.frequency.value = 4200;
  const inG = ac.createGain();
  const out = ac.createGain(); out.gain.value = MUSIC_WET;
  inG.connect(conv); conv.connect(lp); lp.connect(out); out.connect(dest);
  return inG;
}

