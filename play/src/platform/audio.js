const SOUNDS = {
  /** Orb lands: soft round "plop" + muted thud body (Suika-like). */
  drop(_, calm) {
    const pan = panR();
    layer('plop', { gain: calm ? 0.32 : 0.42, rate: 0.82, pan, lp: 2600 });
    if (!calm) layer('thud', { gain: 0.3, rate: rnd(1.0, 1.15), pan, delay: 0.004 });
  },

  /**
   * Merge pop. `note` (chain tally) = next major-scale degree each cascade step.
   * Weight scales with tier: small orbs = light bright pop + kalimba; big planets/stars =
   * deeper plop, warmer marimba, octave-down body and a sub thump.
   */
  merge({ tier = 1, combo = 1, note } = {}, calm) {
    // Round and soft (playtest: the bright kalimba + sped-up pluck read as "screechy"). Notes sit an
    // octave lower than the UI stingers (C3 base) and the climb is capped at ~1.5 octaves.
    const f = note != null
      ? majorFreq(Math.min(10, Math.max(0, note)), 130.81)
      : pentaFreq(Math.min(9, (tier - 1) + (Math.max(1, combo) - 1)), 130.81);
    const k = Math.min(1, Math.max(0, (tier - 1) / 9)); // 0 small .. 1 biggest
    const pan = panR(0.18);
    // transient: the same soft plop the drop uses, never sped up much
    layer('plop', { gain: 0.36 + k * 0.12, rate: 1.05 - k * 0.35, pan, lp: 2400 - k * 1000 });
    // bubble "bloop": sine that glides up a fifth (Suika-style pop), then a warm marimba body on the scale
    tone(f * 2, 0.12, { type: 'sine', gain: 0.1, glideTo: f * 3, attack: 0.003, pan, filter: 1800 });
    marimba(f * 2, { gain: 0.13, pan, noClick: true, send: calm ? 0.05 : 0.1 });
    if (calm) return;
    if (k >= 0.3) tone(f, 0.3 + k * 0.25, { type: 'sine', gain: 0.05 + k * 0.06, attack: 0.004, filter: 700 });
    if (tier >= 6) sub(72 - k * 18, 0.28 + k * 0.2, 0.12 + k * 0.1);
    if (tier >= 5) layer('thud', { gain: 0.18 + k * 0.2, rate: 1.1 - k * 0.3, pan });
  },

  /**
   * Koi Pond water bubble bursting (only when a piece is destroyed without merging): a soft, quick "blip" that
   * glides up, like a real bubble, layered under the comet/supernova sound. Bigger koi pop a little lower.
   */
  bubble({ tier = 1 } = {}, calm) {
    const k = Math.min(1, Math.max(0, (tier - 1) / 9));
    const pan = panR(0.25);
    const f = 620 - k * 220;
    tone(f, 0.07, { type: 'sine', gain: calm ? 0.04 : 0.065, glideTo: f * 1.7, attack: 0.002, pan, filter: 2600 });
    if (!calm) layer('plop', { gain: 0.14, rate: 1.4 - k * 0.2, pan, lp: 3200, minor: true });
  },

  /** Combo multiplier: FM bell + glass sparkle, higher for bigger combos. */
  combo({ combo = 2 } = {}, calm) {
    const f = majorFreq(7 + Math.min(7, Math.max(0, combo - 2)));
    bell(f, { gain: calm ? 0.07 : 0.1 });
    if (calm) return;
    tone(f * 1.5, 0.45, { type: 'triangle', gain: 0.04, delay: 0.05, send: 0.2 });
    layer('tink', { gain: 0.22, rate: 0.9 + Math.min(0.5, (combo - 2) * 0.08), delay: 0.01, minor: true });
    if (combo >= 4) duck(0.6, 0.15, 0.5, false);
  },

  /** Deep "bass hit" when a chain passes your best or enters a new sector. */
  bass({ soft = false } = {}, calm) {
    const s = soft || calm;
    const kk = s ? 0.5 : 1;
    duck(s ? 0.6 : 0.35, 0.3, 0.9);
    layer('boom', { gain: 0.55 * kk, rate: 0.82 });
    sub(58, 0.75, 0.3 * kk);
    if (!s) noise(0.25, { from: 500, to: 70, gain: 0.06, attack: 0.003 });
  },

  /** Top-tier collapse: double boom, whoosh, sub, rising C-major shimmer. */
  supernova(_, calm) {
    duck(0.25, 0.6, 1.4);
    layer('boom', { gain: 0.65, rate: 0.7, variant: 1 });
    if (!calm) layer('boom', { gain: 0.45, rate: 0.95, variant: 2, delay: 0.03 });
    sub(64, 0.9, calm ? 0.2 : 0.32);
    noise(0.9, { from: 2800, to: 120, gain: calm ? 0.1 : 0.18, attack: 0.005, send: 0.3 });
    [0, 4, 7, 12].forEach((s, i) => kalimba(midiHz(72 + s), { gain: 0.09, delay: 0.12 + i * 0.07, send: 0.35 }));
    if (!calm) bell(midiHz(88), { gain: 0.06, delay: 0.42, dur: 1.2 });
  },

  /** Heavy-merge weight (tier 5+ or 3+ orbs at once). */
  impact({ tier = 5 } = {}, calm) {
    const k = Math.min(1, Math.max(0, (tier - 4) / 5));
    layer('boom', { gain: (0.32 + k * 0.3) * (calm ? 0.6 : 1), rate: 1.15 - k * 0.35 });
    if (!calm) sub(110 - k * 45, 0.3 + k * 0.25, 0.14 + k * 0.12);
    if (k > 0.6) duck(0.6, 0.12, 0.4, false);
  },

  /** First-time discovery of a new orb tier: rising kalimba arpeggio + bells + glass. */
  discover({ tier = 2 } = {}, calm) {
    duck(0.4, 0.8, 1.0);
    const root = 60 + [0, 2, 4, 5, 7, 9, 11, 12][Math.min(7, Math.max(0, tier - 2))];
    [0, 4, 7, 12, 16].forEach((s, i) => kalimba(midiHz(root + s), { gain: 0.11, delay: i * 0.075, send: 0.28 }));
    layer('tink', { gain: 0.25, rate: 1.0 });
    if (calm) return;
    bell(midiHz(root + 24), { gain: 0.06, delay: 0.38, dur: 1.2 });
    bell(midiHz(root + 28), { gain: 0.04, delay: 0.46, dur: 1.2 });
    layer('tink', { gain: 0.2, rate: 1.4, delay: 0.38 });
  },

  /** Second cup (+1 drop): a soft two-note kalimba "ding-dong" (a fifth up), a faint bell after it unless Calm. */
  cup(_, calm) {
    [0, 7].forEach((s, i) => kalimba(midiHz(72 + s), { gain: 0.1, delay: i * 0.1, send: 0.22 }));
    if (calm) return;
    bell(midiHz(91), { gain: 0.035, delay: 0.22, dur: 0.9 });
  },

  /** Motes land on a HUD counter: tiny glass tick that climbs through a cascade. */
  collect({ combo = 1 } = {}, calm) {
    const step = Math.min(8, Math.max(0, combo - 1));
    const semis = PENTA[step % 5] + 12 * Math.floor(step / 5);
    if (!layer2('tink', { gain: calm ? 0.1 : 0.16, rate: Math.pow(2, semis / 12) * 0.85, minor: true, pan: panR(0.3) })) {
      tone(pentaFreq(10 + step), 0.09, { gain: 0.07, minor: true });
    }
  },

  /** Rising tide: low swell that pushes up, then a soft thud as the row arrives. */
  tide(_, calm) {
    tone(70, 0.6, { type: 'sine', gain: calm ? 0.16 : 0.24, glideTo: 120, attack: 0.08 });
    noise(0.55, { from: 250, to: 1100, gain: calm ? 0.04 : 0.07, attack: 0.15, send: 0.15 });
    layer('thud', { gain: 0.4, rate: 0.75, delay: 0.42 });
    if (!calm) sub(55, 0.4, 0.16, 0.42);
  },

  /** Sector up / perk / revive: short bright marimba fanfare + glass. */
  perk(_, calm) {
    duck(0.5, 0.4, 0.8);
    [0, 4, 7, 12].forEach((s, i) => marimba(midiHz(67 + s), { gain: 0.13, delay: i * 0.07, send: 0.16 }));
    if (calm) return;
    bell(midiHz(84), { gain: 0.06, delay: 0.28 });
    layer('tink', { gain: 0.2, rate: 1.2, delay: 0.28, minor: true });
  },

  /** Game over: gentle descending marimba that resolves home to C major (not a "fail" buzzer). */
  gameover(_, calm) {
    duck(0.35, 1.2, 1.5);
    [79, 76, 74, 72].forEach((m, i) => marimba(midiHz(m - 12), { gain: 0.13, delay: i * 0.16, dur: 0.7, send: 0.22 }));
    // soft C-major pad under the last note
    [48, 55, 64].forEach((m) => tone(midiHz(m), 1.4, { type: 'triangle', gain: calm ? 0.035 : 0.05, attack: 0.25, delay: 0.48, filter: 900, send: 0.3 }));
    layer('thud', { gain: 0.25, rate: 0.7, delay: 0.48 });
  },

  /** New best / level complete: major-key fanfare with bell crown, glass sparkles and weight. */
  newbest(_, calm) {
    duck(0.3, 1.0, 1.4);
    [0, 4, 7, 12, 16].forEach((s, i) => marimba(midiHz(60 + s), { gain: 0.14, delay: i * 0.07, send: 0.18 }));
    [72, 76, 79, 84].forEach((m) => tone(midiHz(m), 0.9, { type: 'triangle', gain: 0.035, attack: 0.02, delay: 0.36, filter: 3500, send: 0.3 }));
    bell(midiHz(91), { gain: 0.07, delay: 0.38, dur: 1.3 });
    if (calm) return;
    layer('boom', { gain: 0.3, rate: 1.1, delay: 0.36 });
    layer('tink', { gain: 0.22, rate: 1.0, delay: 0.36 });
    layer('tink', { gain: 0.18, rate: 1.33, delay: 0.5 });
    layer('tink', { gain: 0.15, rate: 1.5, delay: 0.64 });
  },

  /** Coin: chip clack + two-note bell ding (B6 -> E7). */
  coin(_, calm) {
    layer('chip', { gain: calm ? 0.2 : 0.3, minor: true, pan: panR(0.25) });
    tone(1975.5, 0.07, { type: 'sine', gain: 0.05, minor: true });
    tone(2637, 0.22, { type: 'sine', gain: 0.055, delay: 0.05, minor: true, send: 0.1 });
    tone(2637 * 2.76, 0.06, { type: 'sine', gain: 0.012, delay: 0.05, minor: true });
  },

  /** UI tap: crisp soft click + tiny pitched blip. */
  ui(_, calm) {
    layer('tap', { gain: calm ? 0.22 : 0.3, minor: true, variant: 1 });
    tone(1046.5, 0.05, { type: 'sine', gain: 0.04, minor: true });
  },
};

/** Like layer() but tells the caller whether a sample played (no automatic fallback). */
function layer2(family, opts) {
  const names = Object.keys(SPRITE).filter((n) => n.startsWith(family));
  return sample(pick(names), opts);
}

// Minimum ms between repeats of the same sound (prevents machine-gun spam).
const THROTTLE = { coin: 35, merge: 25, drop: 40, ui: 40, collect: 45, impact: 60, combo: 60, bass: 120, bubble: 45 };

/** Play a named SFX. Unknown names and locked/muted audio are silently ignored. */
export function playSfx(name, params) {
  if (muted) return;
  const fn = SOUNDS[name];
  if (!fn) return;
  const c = ensureContext();
  if (!c || c.state !== 'running') {
    if (c && c.state === 'suspended') c.resume().catch(() => {});
    return;
  }
  const now = (typeof performance !== 'undefined' ? performance.now() : Date.now());
  const gap = THROTTLE[name] || 0;
  if (gap && lastPlay[name] && now - lastPlay[name] < gap) return;
  lastPlay[name] = now;
  try { fn(params || {}, isCalm()); } catch (_) { /* never let audio break the game */ }
}

