function readBool(key, dflt) {
  try { const v = localStorage.getItem(key); return v == null ? dflt : v === '1'; } catch (_) { return dflt; }
}
function writeBool(key, b) {
  try { localStorage.setItem(key, b ? '1' : '0'); } catch (_) { /* ignore */ }
}

// Calm setting: read from the save (cached) so call sites don't have to pass it.
let calmCache = false, calmReadAt = -1e9;
function isCalm() {
  if (calmOverride != null) return calmOverride;
  const now = Date.now();
  if (now - calmReadAt > 1000) {
    calmReadAt = now;
    try { calmCache = !!JSON.parse(localStorage.getItem(SAVE_KEY) || '{}')?.settings?.calm; } catch (_) { calmCache = false; }
  }
  return calmCache;
}

// ---------------------------------------------------------------------------
// Context + bus graph

function ensureContext() {
  if (ctx) return ctx;
  if (typeof window === 'undefined') return null;
  const AC = window.AudioContext || window.webkitAudioContext;
  if (!AC) return null;
  try {
    ctx = new AC({ latencyHint: 'interactive' });
  } catch (_) {
    try { ctx = new AC(); } catch (__) { ctx = null; return null; }
  }
  try {
    // master -> glue compressor -> limiter -> out
    const glue = ctx.createDynamicsCompressor();
    glue.threshold.value = -20; glue.knee.value = 10; glue.ratio.value = 3;
    glue.attack.value = 0.006; glue.release.value = 0.18;
    const limiter = ctx.createDynamicsCompressor();
    limiter.threshold.value = -3; limiter.knee.value = 0; limiter.ratio.value = 20;
    limiter.attack.value = 0.001; limiter.release.value = 0.08;
    master = ctx.createGain();
    master.gain.value = muted ? 0 : MASTER_VOL;
    master.connect(glue); glue.connect(limiter); limiter.connect(ctx.destination);

    sfxBus = ctx.createGain(); sfxBus.gain.value = nightCalm ? NIGHT_SFX : 1; sfxBus.connect(master);
    minorBus = ctx.createGain(); minorBus.connect(sfxBus);   // ducked under big moments
    musicDuck = ctx.createGain(); musicDuck.connect(master);
    musicBus = ctx.createGain(); musicBus.gain.value = 0; musicBus.connect(musicDuck);

    // small "space" reverb: generated stereo impulse, dark and short
    const conv = ctx.createConvolver();
    conv.buffer = makeImpulse(1.6, 3.2);
    const rvLp = ctx.createBiquadFilter(); rvLp.type = 'lowpass'; rvLp.frequency.value = 4200;
    reverbIn = ctx.createGain(); reverbIn.gain.value = 1;
    reverbIn.connect(conv); conv.connect(rvLp);
    const rvOut = ctx.createGain(); rvOut.gain.value = 0.32; rvLp.connect(rvOut); rvOut.connect(master);

    // music-only reverb that returns INSIDE the music bus, so fades, ducking and Calm apply to its tail too
    musicVerbIn = buildMusicVerb(ctx, musicBus);
  } catch (_) {
    ctx = null; master = null;
    return null;
  }
  decodeSprite();
  return ctx;
}

function makeImpulse(seconds, decay, ac = ctx) {
  const len = Math.floor(ac.sampleRate * seconds);
  const buf = ac.createBuffer(2, len, ac.sampleRate);
  for (let ch = 0; ch < 2; ch++) {
    const d = buf.getChannelData(ch);
    for (let i = 0; i < len; i++) {
      const t = i / len;
      d[i] = (Math.random() * 2 - 1) * Math.pow(1 - t, decay) * (i < 90 ? i / 90 : 1);
    }
  }
  return buf;
}

