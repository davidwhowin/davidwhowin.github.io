/**
 * QA helper: render `seconds` of one backdrop offline at the in-game music level and report levels
 * (peak, RMS, clipped samples, the largest sample-to-sample jump). opts.thunderAt forces a thunder roll.
 */
export async function renderBackdropOffline(id, seconds = 20, sampleRate = 44100, opts = {}) {
  const OAC = (typeof window !== 'undefined') && (window.OfflineAudioContext || window.webkitOfflineAudioContext);
  if (!OAC || !AMBIENCE_IDS.includes(id)) return null;
  const ac = new OAC(2, Math.ceil(seconds * sampleRate), sampleRate);
  const bus = ac.createGain(); bus.gain.value = opts.calm ? MUSIC_VOL * 0.55 : MUSIC_VOL; bus.connect(ac.destination);
  const verbIn = buildMusicVerb(ac, bus);
  const A = createAmbience(ac, id, bus, verbIn, { fadeIn: opts.fadeIn ?? 0, thunderAt: opts.thunderAt });
  // the game ticks every 250 ms with a 0.6 s lookahead; offline we can schedule the whole clip at once
  A.tick(seconds + 1);
  const buf = await ac.startRendering();
  let peak = 0, sum = 0, n = 0, clipped = 0, maxJump = 0;
  const L = buf.getChannelData(0), Rch = buf.getChannelData(1);
  for (let i = 0; i < L.length; i++) {
    const v = Math.max(Math.abs(L[i]), Math.abs(Rch[i]));
    if (v > peak) peak = v;
    if (v >= 1) clipped++;
    sum += L[i] * L[i] + Rch[i] * Rch[i]; n += 2;
    if (i) maxJump = Math.max(maxJump, Math.abs(L[i] - L[i - 1]), Math.abs(Rch[i] - Rch[i - 1]));
  }
  const db = (v) => (v > 0 ? Math.round(200 * Math.log10(v)) / 10 : -Infinity);
  return { ...(opts.keepBuffer ? { buffer: buf } : null), id, seconds, peak: Math.round(peak * 1000) / 1000, peakDb: db(peak), rmsDb: db(Math.sqrt(sum / Math.max(1, n))), clipped, maxJump: Math.round(maxJump * 1e4) / 1e4 };
}

