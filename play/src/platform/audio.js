function newSession(ac, track, dryDest, wetDest, fadeIn) {
  const t0 = ac.currentTime;
  const lv = track.level || 1; // per-song trim so every song sits at a similar loudness
  const S = { id: ++sessionSeq, ac, track, stepIdx: 0, nextAt: t0 + 0.15, noise: null, dead: false, sources: new Set(), lv, fadeT0: t0, fadeIn: fadeIn || 0 };
  S.dry = ac.createGain(); S.wet = ac.createGain();
  for (const g of [S.dry, S.wet]) {
    if (fadeIn) { g.gain.setValueAtTime(0.0001, t0); g.gain.linearRampToValueAtTime(lv, t0 + fadeIn); } else g.gain.value = lv;
  }
  S.dry.connect(dryDest); S.wet.connect(wetDest);
  return S;
}

/** The session's gain at time t, computed from its own fade-in (never read AudioParam.value: WebKit can report a stale value mid-automation). */
function sessionLevel(S, t) {
  if (!S.fadeIn) return S.lv;
  return Math.max(0.0001, S.lv * Math.min(1, Math.max(0, (t - S.fadeT0) / S.fadeIn)));
}

/**
 * End a song for good: it is marked dead (mv/mNoise refuse it), leaves the live registry, fades out
 * over `fade` seconds, every scheduled source is hard-stopped at the end of the fade, and after the
 * fade its gains are pinned to 0 and disconnected. Safe to call twice.
 */
function endSession(S, fade = 1.2) {
  if (!S || S.dead) return;
  S.dead = true;
  liveSessions.delete(S);
  if (cur === S) cur = null;
  const ac = S.ac;
  const t = ac.currentTime, tEnd = t + fade;
  S.endAt = tEnd;
  fadingSessions.add(S);
  for (const g of [S.dry, S.wet]) {
    try {
      g.gain.cancelScheduledValues(0);
      g.gain.setValueAtTime(sessionLevel(S, t), t);
      g.gain.linearRampToValueAtTime(0.0001, tEnd);
      g.gain.setValueAtTime(0, tEnd + 0.02);
    } catch (_) { /* ignore */ }
  }
  for (const src of S.sources) {
    try { src.stop(Math.min(src.__end ?? Infinity, tEnd + 0.05)); } catch (_) { /* already stopped */ }
  }
  setTimeout(() => finishSession(S), (fade + 0.4) * 1000);
}

function finishSession(S) {
  if (!fadingSessions.has(S)) return;
  fadingSessions.delete(S);
  for (const g of [S.dry, S.wet]) {
    try { g.gain.cancelScheduledValues(0); g.gain.value = 0; } catch (_) { /* ignore */ }
    try { g.disconnect(); } catch (_) { /* ignore */ }
  }
  for (const src of S.sources) { try { src.stop(); } catch (_) { /* ignore */ } }
  S.sources.clear();
}

/** End every live song (optionally sparing one). */
function endAllSessions(fade = 1.2, keep = null) {
  for (const S of [...liveSessions]) if (S !== keep) endSession(S, fade);
}

function scheduleUntil(S, tEnd, calm) {
  const tr = S.track;
  const dt = 60 / tr.bpm / tr.div;
  const loop = tr.chords.length * tr.chordSteps;
  while (!S.dead && S.nextAt < tEnd) {
    const i = S.stepIdx, li = i % loop;
    const x = { li, ci: Math.floor(li / tr.chordSteps), s: li % tr.chordSteps, pass: Math.floor(i / loop), calm, dt };
    x.chord = tr.chords[x.ci];
    const t = S.nextAt + (tr.swing && i % 2 ? tr.swing * dt : 0);
    try { tr.step(S, x, t); } catch (_) { /* never let music break the game */ }
    S.stepIdx++;
    S.nextAt += dt;
  }
}

function startSession(fadeIn = 0.25) {
  endAllSessions(1.2); // never more than one song: every other live session fades out
  if (!TRACK_BY_ID[currentId]) currentId = randomEnabled();
  cur = newSession(ctx, TRACK_BY_ID[currentId], musicBus, musicVerbIn || musicBus, fadeIn);
  liveSessions.add(cur);
}

function musicTick() {
  if (!ctx || ctx.state !== 'running' || muted || !musicOn) return;
  if (activeBed() !== 'music') { bedTick(); return; } // a sound backdrop (or Silence) instead of songs
  const fromBackdrop = !!amb;
  if (amb) endAmb(BED_FADE);
  if (cur && cur.dead) cur = null;
  if (!cur) { ensurePlayable(); startSession(fromBackdrop ? BED_FADE : 0.25); }
  // the run picked another song while the context was suspended/interrupted: crossfade to it now
  else if (cur.track.id !== currentId && TRACK_BY_ID[currentId]) startSession();
  if (liveSessions.size > 1) endAllSessions(1.2, cur); // belt and braces
  const now = ctx.currentTime;
  if (cur.nextAt < now) cur.nextAt = now + 0.1; // resume after a stall without a burst of notes
  scheduleUntil(cur, now + LOOKAHEAD, isCalm());
}

function startMusicIfWanted() {
  if (musicTimer || !ctx || !musicBus || muted || !musicOn || yielded || offscreen) return;
  if (typeof document !== 'undefined' && document.hidden) return;
  if (ctx.state !== 'running') return;
  musicBus.gain.cancelScheduledValues(ctx.currentTime);
  musicBus.gain.setValueAtTime(Math.max(0.0001, musicBus.gain.value), ctx.currentTime);
  musicBus.gain.linearRampToValueAtTime(musicLevel(), ctx.currentTime + 0.6);
  if (activeBed() === 'music') {
    ensurePlayable(); // boot/menu/resume: a random ENABLED song (never a fixed default, never a disabled one)
    startSession(0); // the song restarts from its top (the melody starts on beat one); the short bus fade covers the entry
  }
  musicTimer = setInterval(() => { try { musicTick(); } catch (_) { /* ignore */ } }, 250);
  try { musicTick(); } catch (_) { /* ignore */ }
  claimMusic();
}

function stopMusic() {
  if (musicTimer) { clearInterval(musicTimer); musicTimer = null; }
  if (ctx && musicBus) {
    musicBus.gain.cancelScheduledValues(ctx.currentTime);
    musicBus.gain.setTargetAtTime(0, ctx.currentTime, 0.3);
  }
  endAllSessions(1.0);
  cur = null;
  endAmb(1.0);
}

function switchTo(id) {
  if (!TRACK_BY_ID[id]) return;
  const changed = id !== currentId;
  currentId = id;
  if (!musicTimer || !ctx) return;
  if (activeBed() !== 'music') return; // a sound backdrop is playing: the song waits until Music is the backdrop again
  if (ctx.state === 'running') {
    if (changed || !cur) {
      startSession(); // crossfade: old song fades out over 1.2 s while the new one comes straight in
      try { musicTick(); } catch (_) { /* ignore */ }
    }
  } else if (changed) {
    endAllSessions(0.05); // context paused: drop the old song now; musicTick starts the new one on resume
  }
}

// --- one music owner per browser: if the page is loaded twice (e.g. a re-mounted frame), the
// instance that started music most recently wins and the others go quiet until tapped again. ---
const instanceId = Math.random().toString(36).slice(2);
let yielded = false;
let musicChannel = null;
function claimMusic() {
  try {
    if (!musicChannel && typeof BroadcastChannel === 'function') {
      musicChannel = new BroadcastChannel('novadrop.music');
      musicChannel.onmessage = (e) => {
        const m = e && e.data;
        if (m && m.type === 'claim' && m.id !== instanceId && musicTimer) { yielded = true; stopMusic(); }
      };
    }
    if (musicChannel) musicChannel.postMessage({ type: 'claim', id: instanceId });
  } catch (_) { /* ignore */ }
}

