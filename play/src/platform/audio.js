/** 'C4' -> 60 (white keys only, so everything stays in key with the C-major SFX). */
function nm(s) {
  const r = /^([A-G])(\d)$/.exec(s);
  if (!r) throw new Error('bad note ' + s);
  return 12 * (+r[2] + 1) + PC[r[1]];
}
/** "E5:4 G5:2 -:2 | ..." (length in steps, '-' = rest, '|' = bar line) -> { [loopStep]: [midi, steps], length }. */
function melody(src) {
  const map = {}; let pos = 0;
  for (const tok of src.trim().split(/\s+/)) {
    if (tok === '|') continue;
    const [n, l] = tok.split(':');
    const len = +l || 1;
    if (n !== '-') map[pos] = [nm(n), len];
    pos += len;
  }
  Object.defineProperty(map, 'length', { value: pos });
  return map;
}
