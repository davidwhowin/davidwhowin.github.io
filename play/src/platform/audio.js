// Unlock (iOS Safari: resume + silent buffer inside the first user gesture)

let silentPrimed = false;
let statechangeBound = false;

/** Resume the context if needed, then start music once it runs. Idempotent: callable from any path, any number of times. */
function resumeAndStart() {
  const c = ctx;
  if (!c || offscreen) return;
  if (c.state === 'running') { startMusicIfWanted(); return; }
  if (c.state === 'closed') return;
  try { c.resume().then(startMusicIfWanted, () => {}); } catch (_) { /* ignore */ }
}

function unlock() {
  const c = ensureContext();
  if (!c) return;
  if (!statechangeBound) {
    statechangeBound = true;
    // iOS can move the context to 'interrupted'/'suspended' on its own; start music when it comes back
    try { c.addEventListener('statechange', () => { if (c.state === 'running') startMusicIfWanted(); }); } catch (_) { /* ignore */ }
  }
  yielded = false; // a tap in THIS page makes it the music owner again
  if (!silentPrimed || c.state !== 'running') {
    silentPrimed = true;
    try {
      const b = c.createBuffer(1, 1, 22050);
      const s = c.createBufferSource();
      s.buffer = b; s.connect(c.destination); s.start(0);
    } catch (_) { /* ignore */ }
  }
  resumeAndStart();
}

/** Bind listeners that create/resume the AudioContext on user gestures, and preload samples. */
export function initAudio() {
  if (unlockBound || typeof window === 'undefined') return;
  unlockBound = true;
  fetchSprite();
  // Kept bound for the whole session (cheap and idempotent): iOS may suspend/interrupt the context
  // later, and a tap is the only reliable way to resume it.
  const events = ['pointerdown', 'touchstart', 'touchend', 'keydown', 'mousedown'];
  const handler = () => { try { unlock(); } catch (_) { /* ignore */ } };
  events.forEach((e) => window.addEventListener(e, handler, { capture: true, passive: true }));
  // Re-resume after returning from background (iOS suspends the context); pause music while hidden.
  document.addEventListener('visibilitychange', () => {
    if (!ctx) return;
    if (document.hidden) { stopMusic(); return; }
    resumeAndStart();
  });
  // Page leaving (navigation, frame removed, bfcache): silence this instance's music for good.
  window.addEventListener('pagehide', () => { if (ctx) stopMusic(); });
  window.addEventListener('pageshow', (e) => { if (ctx && e && e.persisted && !document.hidden) resumeAndStart(); });
  startFrameWatch();
}

// Off-screen watchdog. A copy of the page that is still loaded but not shown (e.g. an older
// version left in a hidden frame after the page was updated) gets no 'visibilitychange', so it
// would keep playing under the visible copy. Browsers stop animation frames for frames that are
// not rendered: no frame for OFFSCREEN_MS => this copy is off screen => silence its music.
const OFFSCREEN_MS = 1500;
let lastFrameAt = null; // null = watchdog unavailable (tests / no rAF): never treat as off screen
let offscreen = false;
function startFrameWatch() {
  if (typeof requestAnimationFrame !== 'function' || typeof performance === 'undefined') return;
  const beat = () => {
    lastFrameAt = performance.now();
    if (offscreen) { offscreen = false; if (ctx && !document.hidden) resumeAndStart(); }
    requestAnimationFrame(beat);
  };
  requestAnimationFrame(beat);
  setInterval(() => {
    if (lastFrameAt == null || offscreen) return;
    if (performance.now() - lastFrameAt > OFFSCREEN_MS) { offscreen = true; if (ctx) stopMusic(); }
  }, 500);
}

export function setMuted(b) {
  muted = !!b;
  writeBool(MUTE_KEY, muted);
  if (master && ctx) {
    master.gain.cancelScheduledValues(ctx.currentTime);
    master.gain.setTargetAtTime(muted ? 0 : MASTER_VOL, ctx.currentTime, 0.02);
  }
  if (muted) stopMusic(); else startMusicIfWanted();
}
