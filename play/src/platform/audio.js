/** Karplus-Strong string, rendered once per note into a buffer (cheap) and cached per context. */
function ksBuffer(ac, m) {
  const cache = ac.__novaKs || (ac.__novaKs = new Map());
  const hit = cache.get(m);
  if (hit) return hit;
  const sr = ac.sampleRate, f = midiHz(m);
  const N = Math.max(2, Math.round(sr / f - 0.5));
  const len = Math.floor(sr * 1.8);
  const buf = ac.createBuffer(1, len, sr);
  const d = buf.getChannelData(0);
  let lp = 0;
  for (let i = 0; i < N; i++) { lp = lp * 0.55 + (Math.random() * 2 - 1) * 0.45; d[i] = lp; } // soft (thumb) pluck
  for (let i = N; i < len; i++) d[i] = 0.997 * 0.5 * (d[i - N] + (i - N - 1 >= 0 ? d[i - N - 1] : 0));
  let pk = 0;
  for (let i = 0; i < len; i++) pk = Math.max(pk, Math.abs(d[i]));
  if (pk > 0) for (let i = 0; i < len; i++) d[i] /= pk;
  const out = { buf, rate: f / (sr / (N + 0.5)) }; // the averaging filter adds half a sample of delay
  cache.set(m, out);
  return out;
}
/** Plucked nylon guitar (Karplus-Strong) with a warm lowpass. */
function mPluck(S, t, m, lvl, o = {}) {
  if (S.dead) return;
  const ac = S.ac;
  const { buf, rate } = ksBuffer(ac, m);
  const dur = o.dur ?? 1.4;
  const src = ac.createBufferSource(); src.buffer = buf;
  if (src.playbackRate) src.playbackRate.setValueAtTime(rate, t);
  const f = ac.createBiquadFilter(); f.type = 'lowpass'; f.frequency.setValueAtTime(o.lp ?? 3400, t); f.Q.value = 0.5;
  const g = ac.createGain();
  g.gain.setValueAtTime(lvl, t);
  g.gain.setValueAtTime(lvl, t + Math.max(0.01, dur - 0.12));
  g.gain.linearRampToValueAtTime(0.0001, t + dur);
  src.connect(f); f.connect(g);
  let out = g;
  if (o.pan && ac.createStereoPanner) { out = ac.createStereoPanner(); out.pan.value = o.pan; g.connect(out); }
  out.connect(S.dry);
  let s = null;
  if (o.wet) { s = ac.createGain(); s.gain.value = o.wet; g.connect(s); s.connect(S.wet); }
  src.onended = () => { S.sources.delete(src); try { g.disconnect(); if (out !== g) out.disconnect(); if (s) s.disconnect(); } catch (_) { /* ignore */ } };
  src.start(t); src.stop(t + dur + 0.02);
  track(S, src, t + dur + 0.02);
}
/** Guitar chord: the notes plucked `gap` seconds apart, low to high (a negative gap strums back up, high to low). */
