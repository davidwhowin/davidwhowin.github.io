// Nova Drop — Web Audio SFX engine.
//
// Hybrid design (see assets/sfx/CREDITS.md):
//   * sampled transients/textures (CC0 Kenney sprite: plops, pops, thuds, booms, glass, chips, taps)
//   * synthesized tonal layers that are always in C major (marimba / kalimba / FM bell), so every
//     reward stinger sits in the same key as the seven generative café songs (one picked per run)
//   * per-play pitch (+-5%) and gain variation on samples, random pan, tier-dependent weight
//   * bus glue compressor + brick-wall limiter, a small synthetic reverb, and ducking for big moments
// If the sprite can't be fetched/decoded (offline, old browser), every sample layer falls back to
// a synth substitute, so the game is never silent. Nothing here touches the DOM at import time,
// so node tests can import it.

