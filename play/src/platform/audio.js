// Sprite loading (fetch early, decode once the context exists)

function preferredFormats() {
  try {
    const a = document.createElement('audio');
    const ogg = a.canPlayType && a.canPlayType('audio/ogg; codecs="vorbis"');
    // Safari reports "maybe" for ogg on some versions; WAV always decodes there (artifacts cannot serve .m4a).
    const isSafari = /^((?!chrome|android|crios|fxios).)*safari/i.test(navigator.userAgent || '');
    if (ogg && !isSafari) return ['ogg', 'wav'];
  } catch (_) { /* ignore */ }
  return ['wav', 'ogg'];
}

async function fetchSprite() {
  if (spriteState !== 'idle' || typeof fetch !== 'function') return;
  spriteState = 'loading';
  for (const fmt of preferredFormats()) {
    try {
      const res = await fetch(SPRITE_URLS[fmt]);
      if (!res.ok) continue;
      spriteBytes = { fmt, data: await res.arrayBuffer(), alt: fmt === 'ogg' ? 'wav' : 'ogg' };
      decodeSprite();
      return;
    } catch (_) { /* try next */ }
  }
  spriteState = 'failed';
}

function decodeAudio(data) {
  return new Promise((resolve, reject) => {
    try {
      const p = ctx.decodeAudioData(data, resolve, reject);
      if (p && typeof p.then === 'function') p.then(resolve, reject);
    } catch (e) { reject(e); }
  });
}

async function decodeSprite() {
  if (!ctx || !spriteBytes || sprite) return;
  const job = spriteBytes; spriteBytes = null;
  try {
    sprite = await decodeAudio(job.data);
    spriteState = 'ready'; spriteFormat = job.fmt;
  } catch (_) {
    // decode failed (e.g. no Vorbis): try the other container once
    if (job.alt) {
      try {
        const res = await fetch(SPRITE_URLS[job.alt]);
        if (res.ok) { sprite = await decodeAudio(await res.arrayBuffer()); spriteState = 'ready'; spriteFormat = job.alt; return; }
      } catch (__) { /* fall through */ }
    }
    spriteState = 'failed';
  }
}

