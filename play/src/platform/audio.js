// Primitives

const rnd = (a, b) => a + Math.random() * (b - a);
const pick = (arr) => arr[(Math.random() * arr.length) | 0];
const midiHz = (m) => 440 * Math.pow(2, (m - 69) / 12);

function canVoice(minor) { return activeVoices < (minor ? MINOR_VOICES : MAX_VOICES); }
function voiceStart(node, g) {
  activeVoices++;
  node.onended = () => { activeVoices--; try { g.disconnect(); } catch (_) {} };
}

/** Optional stereo pan; returns the node to connect the voice into. */
function outNode(dest, pan) {
  if (!pan || !ctx.createStereoPanner) return dest;
  const p = ctx.createStereoPanner();
  p.pan.value = Math.max(-1, Math.min(1, pan));
  p.connect(dest);
  return p;
}

/**
 * Play a sprite slot. opts: { gain, rate, delay, pan, minor, lp, send }
 * rate gets +-5% random variation unless opts.exact. Returns false when the sprite isn't ready.
 */
function sample(name, opts = {}) {
  const slot = SPRITE[name];
  if (!sprite || !slot || !ctx) return false;
  if (!canVoice(opts.minor)) return true; // ready, just over budget: skip quietly
  const t0 = ctx.currentTime + (opts.delay || 0);
  const src = ctx.createBufferSource();
  src.buffer = sprite;
  const rate = (opts.rate || 1) * (opts.exact ? 1 : rnd(0.95, 1.05));
  src.playbackRate.setValueAtTime(rate, t0);
  const g = ctx.createGain();
  const peak = (opts.gain ?? 0.5) * (opts.exact ? 1 : rnd(0.84, 1.0));
  const len = slot[1] / rate;
  g.gain.setValueAtTime(0.0001, t0);
  g.gain.linearRampToValueAtTime(peak, t0 + 0.002);
  g.gain.setValueAtTime(peak, t0 + Math.max(0.003, len - 0.02));
  g.gain.linearRampToValueAtTime(0.0001, t0 + len + 0.005);
  let node = src;
  if (opts.lp) {
    const f = ctx.createBiquadFilter(); f.type = 'lowpass'; f.frequency.value = opts.lp; f.Q.value = 0.5;
    src.connect(f); node = f;
  }
  node.connect(g);
  g.connect(outNode(opts.minor ? minorBus : sfxBus, opts.pan));
  if (opts.send && reverbIn) { const s = ctx.createGain(); s.gain.value = opts.send; g.connect(s); s.connect(reverbIn); }
  voiceStart(src, g);
  src.start(t0, Math.max(0, slot[0] - 0.003), slot[1] + 0.006);
  return true;
}

/**
 * One enveloped oscillator note.
 * opts: { type, gain, attack, delay, glideTo, detune, filter, pan, minor, send, fm: [ratio, index] }
 */
function tone(freq, dur, opts = {}) {
  if (!ctx || !master || !canVoice(opts.minor)) return;
  const t0 = ctx.currentTime + (opts.delay || 0);
  const osc = ctx.createOscillator();
  const g = ctx.createGain();
  osc.type = opts.type || 'sine';
  osc.frequency.setValueAtTime(freq, t0);
  if (opts.detune) osc.detune.value = opts.detune;
  if (opts.glideTo) osc.frequency.exponentialRampToValueAtTime(Math.max(20, opts.glideTo), t0 + dur);
  let mod = null;
  if (opts.fm) {
    // FM bell: modulator at ratio*f, index decays fast -> bright strike, pure tail
    mod = ctx.createOscillator();
    const mg = ctx.createGain();
    mod.frequency.setValueAtTime(freq * opts.fm[0], t0);
    mg.gain.setValueAtTime(freq * opts.fm[1], t0);
    mg.gain.exponentialRampToValueAtTime(Math.max(0.01, freq * 0.02), t0 + dur * 0.6);
    mod.connect(mg); mg.connect(osc.frequency);
    mod.start(t0); mod.stop(t0 + dur + 0.05);
  }
  const peak = opts.gain ?? 0.2;
  const atk = opts.attack ?? 0.006;
  g.gain.setValueAtTime(0.0001, t0);
  g.gain.exponentialRampToValueAtTime(peak, t0 + atk);
  g.gain.exponentialRampToValueAtTime(0.0001, t0 + dur);
  let node = osc;
  if (opts.filter) {
    const f = ctx.createBiquadFilter(); f.type = 'lowpass'; f.frequency.value = opts.filter; f.Q.value = 0.7;
    osc.connect(f); node = f;
  }
  node.connect(g);
  g.connect(outNode(opts.minor ? minorBus : sfxBus, opts.pan));
  if (opts.send && reverbIn) { const s = ctx.createGain(); s.gain.value = opts.send; g.connect(s); s.connect(reverbIn); }
  voiceStart(osc, g);
  osc.start(t0);
  osc.stop(t0 + dur + 0.05);
}

/** Filtered noise burst (whooshes, swells). */
function noise(dur, opts = {}) {
  if (!ctx || !master || !canVoice(opts.minor)) return;
  const t0 = ctx.currentTime + (opts.delay || 0);
  const len = Math.max(1, Math.floor(ctx.sampleRate * dur));
  const buf = ctx.createBuffer(1, len, ctx.sampleRate);
  const data = buf.getChannelData(0);
  for (let i = 0; i < len; i++) data[i] = Math.random() * 2 - 1;
  const src = ctx.createBufferSource();
  src.buffer = buf;
  const f = ctx.createBiquadFilter();
  f.type = opts.filterType || 'lowpass';
  f.frequency.setValueAtTime(opts.from || 1200, t0);
  if (opts.to) f.frequency.exponentialRampToValueAtTime(opts.to, t0 + dur);
  f.Q.value = opts.q || 0.8;
  const g = ctx.createGain();
  const peak = opts.gain ?? 0.15;
  g.gain.setValueAtTime(0.0001, t0);
  g.gain.exponentialRampToValueAtTime(peak, t0 + (opts.attack ?? 0.01));
  g.gain.exponentialRampToValueAtTime(0.0001, t0 + dur);
  src.connect(f); f.connect(g); g.connect(opts.minor ? minorBus : sfxBus);
  if (opts.send && reverbIn) { const s = ctx.createGain(); s.gain.value = opts.send; g.connect(s); s.connect(reverbIn); }
  voiceStart(src, g);
  src.start(t0);
  src.stop(t0 + dur + 0.05);
}

// --- instruments (all tonal layers are synth so they stay in key) ---

/** Marimba: warm fundamental + 4th-partial "wood" ping + tiny mallet click. */
function marimba(f, opts = {}) {
  const g = opts.gain ?? 0.14, d = opts.delay || 0;
  const dur = opts.dur ?? Math.max(0.22, Math.min(0.7, 120 / f));
  tone(f, dur, { type: 'sine', gain: g, attack: 0.003, delay: d, pan: opts.pan, send: opts.send ?? 0.12 });
  tone(f * 3.93, dur * 0.25, { type: 'sine', gain: g * 0.18, attack: 0.002, delay: d, pan: opts.pan });
  if (!opts.noClick) tone(f * 9.2, 0.03, { type: 'sine', gain: g * 0.12, attack: 0.001, delay: d });
}

/** Kalimba / glass: bright, slightly inharmonic, quick bloom. */
function kalimba(f, opts = {}) {
  const g = opts.gain ?? 0.12, d = opts.delay || 0;
  const dur = opts.dur ?? 0.45;
  tone(f, dur, { type: 'triangle', gain: g, attack: 0.002, delay: d, pan: opts.pan, send: opts.send ?? 0.18, filter: 5200 });
  tone(f * 2.02, dur * 0.5, { type: 'sine', gain: g * 0.35, attack: 0.002, delay: d, pan: opts.pan });
  tone(f * 5.4, 0.08, { type: 'sine', gain: g * 0.14, attack: 0.001, delay: d });
}

/** FM bell (combo, sparkle). */
function bell(f, opts = {}) {
  const g = opts.gain ?? 0.1, d = opts.delay || 0;
  tone(f, opts.dur ?? 0.9, { type: 'sine', gain: g, attack: 0.002, delay: d, fm: [3.5, 2.2], pan: opts.pan, send: opts.send ?? 0.28 });
  tone(f * 2, 0.35, { type: 'sine', gain: g * 0.3, attack: 0.002, delay: d });
}

/** Sub-bass weight: sine thump with downward glide (felt more than heard on phones; the 2nd harmonic carries it). */
function sub(f, dur, gain, delay = 0) {
  tone(f, dur, { type: 'sine', gain, glideTo: f * 0.62, attack: 0.004, delay });
  tone(f * 2, dur * 0.6, { type: 'triangle', gain: gain * 0.28, glideTo: f * 1.3, attack: 0.004, delay, filter: 420 });
}

/** Duck music (and optionally the minor SFX bus) under a big moment. */
function duck(depth = 0.35, hold = 0.35, release = 0.9, minorToo = true) {
  if (!ctx) return;
  const t = ctx.currentTime;
  const nodes = minorToo ? [musicDuck, minorBus] : [musicDuck];
  for (const n of nodes) {
    if (!n) continue;
    const lvl = n === minorBus ? Math.max(depth, 0.55) : depth;
    n.gain.cancelScheduledValues(t);
    n.gain.setValueAtTime(n.gain.value, t);
    n.gain.linearRampToValueAtTime(lvl, t + 0.03);
    n.gain.setValueAtTime(lvl, t + 0.03 + hold);
    n.gain.linearRampToValueAtTime(1, t + 0.03 + hold + release);
  }
}

// Scales (C major everywhere).
const PENTA = [0, 2, 4, 7, 9];
function pentaFreq(step, base = 261.63 /* C4 */) {
  const oct = Math.floor(step / PENTA.length);
  const semis = PENTA[((step % PENTA.length) + PENTA.length) % PENTA.length] + oct * 12;
  return base * Math.pow(2, semis / 12);
}
const MAJOR = [0, 2, 4, 5, 7, 9, 11];
function majorFreq(step, base = 261.63 /* C4 */) {
  const oct = Math.floor(step / MAJOR.length);
  const semis = MAJOR[((step % MAJOR.length) + MAJOR.length) % MAJOR.length] + oct * 12;
  return base * Math.pow(2, semis / 12);
}

// Synth stand-ins for sample slots when the sprite is unavailable.
const FALLBACK = {
  plop: (o) => { tone(320 * (o.rate || 1), 0.12, { gain: 0.2 * (o.gain ?? 0.5) * 2, glideTo: 170 * (o.rate || 1), delay: o.delay }); },
  pop: (o) => { tone(900 * (o.rate || 1), 0.06, { gain: 0.12, glideTo: 520, delay: o.delay }); noise(0.03, { from: 4000, to: 1500, gain: 0.04, delay: o.delay }); },
  thud: (o) => { tone(110, 0.14, { gain: 0.22 * (o.gain ?? 0.5) * 2, glideTo: 60, delay: o.delay }); },
  boom: (o) => { tone(80 * (o.rate || 1), 0.45, { gain: 0.3 * (o.gain ?? 0.5) * 2, glideTo: 38, delay: o.delay }); noise(0.25, { from: 600, to: 80, gain: 0.08, delay: o.delay }); },
  tink: (o) => { tone(2000 * (o.rate || 1), 0.1, { gain: 0.05, delay: o.delay, minor: o.minor }); },
  chip: (o) => { noise(0.04, { from: 7000, filterType: 'bandpass', q: 4, gain: 0.06, delay: o.delay, minor: true }); },
  tap: (o) => { tone(660, 0.05, { gain: 0.08, glideTo: 880, delay: o.delay, minor: true }); },
};
/** Play a random variant of a sample family (plop -> plop1/plop2), falling back to synth. */
function layer(family, opts = {}) {
  const names = Object.keys(SPRITE).filter((n) => n.startsWith(family));
  if (sample(opts.variant ? family + opts.variant : pick(names), opts)) return;
  const fb = FALLBACK[family]; if (fb) fb(opts);
}

const panR = (w = 0.18) => rnd(-w, w);

